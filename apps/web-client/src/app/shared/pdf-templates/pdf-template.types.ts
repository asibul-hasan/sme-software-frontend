import { ColumnDef } from '../components/common-table';

export type PdfModuleCode = 'SYS' | 'FIN' | 'HRM' | 'INV' | 'SAL' | 'PUR' | 'RPT';
export type PdfPageOrientation = 'portrait' | 'landscape';
export type PdfPageSize = 'a4' | 'letter' | 'legal';

/**
 * A single row in a summary / key-value block.
 */
export interface PdfSummaryRow {
  label: string;
  value: unknown;
  colspan?: number; // how many label+value pairs this row spans in a grid
}

/**
 * Supported section types for a PDF page.
 */
export type PdfSectionType =
  | 'title'
  | 'subtitle'
  | 'text'
  | 'table'
  | 'summary'
  | 'separator'
  | 'signatures'
  | 'spacer'
  | 'custom';

/**
 * Base interface for every PDF section.
 */
export interface PdfBaseSection {
  type: PdfSectionType;
}

/**
 * Title section — centered or left-aligned large text.
 */
export interface PdfTitleSection extends PdfBaseSection {
  type: 'title';
  text: string;
  align?: 'left' | 'center' | 'right';
  fontSize?: number;
}

/**
 * Subtitle section — smaller than title, used for dates, filters, branch info.
 */
export interface PdfSubtitleSection extends PdfBaseSection {
  type: 'subtitle';
  text: string;
  align?: 'left' | 'center' | 'right';
}

/**
 * Plain text / paragraph section.
 */
export interface PdfTextSection extends PdfBaseSection {
  type: 'text';
  text: string;
  align?: 'left' | 'center' | 'right';
}

/**
 * Table section — uses the same ColumnDef contract as app-common-table.
 */
export interface PdfTableSection<Row = Record<string, unknown>> extends PdfBaseSection {
  type: 'table';
  columns: ColumnDef[];
  rows: Row[];
  title?: string;
  showRowNumbers?: boolean;
  /**
   * If true, the table auto-calculates landscape when columns exceed a threshold.
   */
  autoLandscape?: boolean;
}

/**
 * Summary section — key/value grid (e.g., report totals, filter criteria).
 */
export interface PdfSummarySection extends PdfBaseSection {
  type: 'summary';
  title?: string;
  rows: PdfSummaryRow[];
  /**
   * Number of label+value pairs per row. Default 2.
   */
  columnsPerRow?: number;
}

/**
 * Horizontal line / separator.
 */
export interface PdfSeparatorSection extends PdfBaseSection {
  type: 'separator';
  thickness?: number;
  color?: [number, number, number];
}

/**
 * Vertical spacer.
 */
export interface PdfSpacerSection extends PdfBaseSection {
  type: 'spacer';
  height: number; // mm
}

/**
 * Signature block — three slots: Prepared By, Checked By, Approved By.
 */
export interface PdfSignaturesSection extends PdfBaseSection {
  type: 'signatures';
  labels?: [string, string, string];
}

/**
 * Custom draw section — gives raw jsPDF access for advanced needs.
 */
export interface PdfCustomSection extends PdfBaseSection {
  type: 'custom';
  draw: (doc: import('jspdf').jsPDF, startY: number, pageWidth: number, marginX: number, helpers: { drawHeader: () => void, drawPageFooter: () => void }) => number;
}

/**
 * Union of all section types.
 */
export type PdfTemplateSection =
  | PdfTitleSection
  | PdfSubtitleSection
  | PdfTextSection
  | PdfTableSection
  | PdfSummarySection
  | PdfSeparatorSection
  | PdfSpacerSection
  | PdfSignaturesSection
  | PdfCustomSection;

/**
 * A reusable PDF report template.
 *
 * Context = the input data (e.g., trial-balance response, employee record).
 * The template turns that context into an ordered list of sections.
 */
export interface PdfTemplate<Context = unknown> {
  /** Unique template id, e.g. 'FIN.trial-balance' */
  id: string;
  /** ERP module that owns this template */
  module: PdfModuleCode | ((context: Context) => PdfModuleCode);
  /** Form id for permission / routing tracking */
  formId: string | ((context: Context) => string);
  /** Report title shown in the header and filename */
  title: string | ((context: Context) => string);
  /** Base filename (without .pdf extension) */
  fileName: string | ((context: Context) => string);
  /** Page orientation */
  orientation?: PdfPageOrientation | ((context: Context) => PdfPageOrientation | undefined);
  /** Page size */
  pageSize?: PdfPageSize | ((context: Context) => PdfPageSize | undefined);
  /** Optional subtitle builder shown under the company header */
  buildSubTitle?(context: Context): string;
  /** Build all sections from the context */
  buildSections(context: Context): PdfTemplateSection[];
  /** Whether to include the standard three-signature footer */
  showSignatures?: boolean | ((context: Context) => boolean | undefined);
  /** Whether to include the standard page footer (page number + "Generated by Aidly ERP") */
  showPageFooter?: boolean | ((context: Context) => boolean | undefined);
}

/**
 * Factory that produces a PdfTemplate for a given context shape.
 * Useful when the column schema is known but the data is dynamic.
 */
export type PdfTemplateFactory<Context> = (context: Context) => PdfTemplate<Context>;

/**
 * A generic context structure for reports that don't need a specific schema
 * and just want to generate standard sections dynamically.
 */
export interface PdfReportContext {
  module: PdfModuleCode;
  formId: string;
  title: string;
  fileName: string;
  orientation?: PdfPageOrientation;
  pageSize?: PdfPageSize;
  showSignatures?: boolean;
  showPageFooter?: boolean;
  subTitle?: string;
  sections: PdfTemplateSection[];
}
